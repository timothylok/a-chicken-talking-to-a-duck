import type { Metadata } from "next";
import TrafficLight from "../components/TrafficLight";
import { loadAiBubble } from "../lib/aiBubble";

export const metadata: Metadata = {
  title: "AI Bubble Gauges",
  description: "Five gauges of AI-cycle strain from SEC filings and market data, scored daily.",
};

const BANDS = "0-33 green, 34-66 amber, 67-100 red";

export default function AiBubblePage() {
  const b = loadAiBubble();

  return (
    <main>
      <a className="back-link" href="/dashboard">← Risk dashboard</a>
      <h1>AI Bubble Gauges</h1>
      {!b ? (
        <div className="error">No data yet -- it is generated by the daily dashboard run.</div>
      ) : (
        <>
          <div className="bubble-head">
            <TrafficLight light={b.compositeLight} />
            <span className="bubble-score">{b.composite ?? "N/A"}</span>
            <span className="coverage">/ 100 -- {b.coverage}</span>
          </div>
          <p className="tagline">
            Higher = more bubble-like. Each metric scores 0 at its calm threshold and 1 at its stretched one
            (linear between); a gauge is the mean of its metrics and the composite the mean of the gauges, all
            computed in code with no LLM ({BANDS}). Thresholds are fixed and documented in ops/ai_bubble.py --
            a reading of strain, not a forecast or advice.
          </p>
          <div className="grid">
            {b.gauges.map((g) => (
              <section className="card" key={g.id}>
                <div className="card-head">
                  <span className="ticker">
                    <TrafficLight light={g.light} /> {g.name}
                  </span>
                  <span className="composite">{g.score != null ? Math.round(g.score * 100) : "N/A"}</span>
                </div>
                <div className="kpi-list">
                  {g.metrics.map((m) => (
                    <div className="bubble-metric" key={m.id}>
                      <div className="kpi-row">
                        <TrafficLight light={m.light} />
                        <span className="kpi-name">{m.name}</span>
                        <span className="bubble-value">{m.display}</span>
                      </div>
                      <div className="bubble-meta">
                        {m.note && <>{m.note} </>}
                        Calm at {m.lo}, stretched at {m.hi}. {m.source}
                        {m.asOf && <>, as of {m.asOf}</>}.
                        {m.stale && <span className="stale">stale -- last good value</span>}
                      </div>
                    </div>
                  ))}
                </div>
              </section>
            ))}
          </div>
          <section className="sectors">
            <h2>Context (not scored)</h2>
            <ul className="bubble-context">
              {b.context.spy && (
                <li>
                  Concentration: Mag 7 = <strong>{b.context.spy.mag7Weight}%</strong> of SPY, top 10 ={" "}
                  {b.context.spy.top10Weight}%, HHI {b.context.spy.hhi} across {b.context.spy.holdings} holdings (
                  {b.context.spy.source}, {b.context.spy.asOf})
                  {b.context.spy.stale && <span className="stale">stale</span>}
                </li>
              )}
              {b.context.vix && (
                <li>
                  VIX {b.context.vix.level ?? "N/A"}, {b.context.vix.percentile10y ?? "N/A"}th percentile of 10 years --
                  regime {b.context.vix.regime ?? "N/A"} (<a href="/dashboard">volatility panel</a>)
                </li>
              )}
              {b.context.headlines && (
                <li>
                  &ldquo;AI bubble&rdquo; headlines: {b.context.headlines.today} today, 7-day average{" "}
                  {b.context.headlines.avg7} ({b.context.headlines.source}; the feed caps at about 100)
                  {b.context.headlines.stale && <span className="stale">stale</span>}
                </li>
              )}
            </ul>
          </section>
          <p className="generated">Generated {b.generatedAt} NZT.</p>
        </>
      )}
    </main>
  );
}
